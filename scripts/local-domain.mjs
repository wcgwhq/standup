// npm run domain: serve this site at https://<name>.localhost/ through the Homebrew Caddy.
// It writes one file, <brew prefix>/etc/caddy.d/<name>.caddy, then validates and reloads Caddy.
// Without a running brew Caddy it changes nothing. `npm run domain -- --remove` undoes it.
// A <name>.caddy that wcgw did not write is never replaced or removed.
// The last line it prints is always the URL that works.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { devPort } from '../site.config.mjs';

const { name } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const pretty = `https://${name}.localhost/`;
const fallback = `http://${name}.localhost:${devPort}/`;
// Tests point WCGW_CADDY_DIR at a temp folder: the file is written there and no Caddy is touched.
const testDir = process.env.WCGW_CADDY_DIR;
// Any wcgw site's first line, so a moved or recreated site can still replace its own file.
const GENERATED = /^# Generated by .+\/scripts\/local-domain\.mjs — do not edit by hand\.$/;

/** True when the file is missing or a wcgw site wrote it. */
const ours = (/** @type {string} */ file) =>
  !existsSync(file) || GENERATED.test(readFileSync(file, 'utf8').split('\n', 1)[0]);

/** stdout of a command, or '' when it is missing or fails. */
const output = (/** @type {string} */ command, /** @type {string[]} */ args) => {
  const result = spawnSync(command, args, { encoding: 'utf8' });
  return result.status === 0 ? result.stdout.trim() : '';
};

const { url, note = '', error = '' } = await run(process.argv.includes('--remove'));
if (note) console.log(note);
if (error) {
  console.error(error);
  process.exitCode = 1;
}
console.log(url);

/** @param {boolean} remove */
async function run(remove) {
  // node --test sets NODE_TEST_CONTEXT. A test that forgot the seam must never reach the real Caddy.
  if (!testDir && process.env.NODE_TEST_CONTEXT) {
    return { url: fallback, error: 'Tests must set WCGW_CADDY_DIR. The real Caddy was not touched.' };
  }
  const prefix = testDir ? '' : output('brew', ['--prefix']);
  if (!testDir && !(prefix && output('caddy', ['version']))) {
    const setup = 'brew install caddy && brew services start caddy && caddy trust';
    return { url: fallback, note: remove ? '' : `Caddy is not installed. For ${pretty}: ${setup}` };
  }
  const caddyDir = testDir || path.join(prefix, 'etc', 'caddy.d');
  const caddyfile = path.join(prefix, 'etc', 'Caddyfile');
  const site = path.join(caddyDir, `${name}.caddy`);
  // Other projects keep hand-written files in the same folder.
  if (!ours(site)) {
    const fix = remove ? '' : ` For ${pretty}, remove that file or rename this site.`;
    return { url: fallback, note: `${site} was not made by wcgw, so it was left alone.${fix}` };
  }
  const live = !testDir && (await adminAnswers());

  /** caddy validate|reload on the brew Caddyfile: '' when it worked, else Caddy's last log message. */
  const caddy = (/** @type {string} */ command) => {
    const result = spawnSync('caddy', [command, '--config', caddyfile], { encoding: 'utf8' });
    if (result.status === 0) return '';
    const last = (result.stderr ?? '').trim().split('\n').at(-1) || `caddy ${command} failed`;
    try {
      return JSON.parse(last).msg ?? last;
    } catch {
      return last;
    }
  };

  if (remove) {
    rmSync(site, { force: true });
    const failed = live && caddy('reload');
    return { url: fallback, error: failed ? `Caddy reload failed: ${failed}` : '' };
  }
  if (!testDir && !live) {
    return { url: fallback, note: `Caddy is not running. For ${pretty}: brew services start caddy` };
  }
  const include = `import ${caddyDir}/*.caddy`;
  if (!testDir && !readFileSync(caddyfile, 'utf8').includes(include)) {
    return { url: fallback, note: `For ${pretty}, add this line to ${caddyfile}: ${include}` };
  }

  // Caddy listens on every interface, so the guard keeps the site on this Mac. Vite listens on
  // ::1, so the upstream is localhost (never 127.0.0.1) and the port is a literal number.
  mkdirSync(caddyDir, { recursive: true });
  writeFileSync(
    site,
    `# Generated by ${fileURLToPath(import.meta.url)} — do not edit by hand.
${name}.localhost {
\ttls internal
\t@offbox not remote_ip 127.0.0.1 ::1
\tabort @offbox
\treverse_proxy localhost:${devPort}
}
`,
  );
  const failed = !testDir && (caddy('validate') || caddy('reload'));
  if (failed) {
    rmSync(site, { force: true });
    return { url: fallback, error: `Caddy refused ${site}: ${failed}` };
  }
  return { url: pretty };
}

/** True when the brew Caddy's admin API answers, i.e. Caddy is running. */
async function adminAnswers() {
  try {
    const response = await fetch('http://localhost:2019/config/', { signal: AbortSignal.timeout(2000) });
    await response.body?.cancel();
    return true;
  } catch {
    return false;
  }
}
